def _open_existing_directory(path: Path) -> int:
    """Pin each resolved parent component without following links or creating it."""
    fd = os.open(path.anchor, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
    try:
        for part in path.parts[1:]:
            next_fd = os.open(part, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW, dir_fd=fd)
            os.close(fd)
            fd = next_fd
        return fd
    except BaseException:
        os.close(fd)
        raise


def _write_workspace_file(root_fd: int, relative: str, text: str, force: bool) -> None:
    parts = Path(relative).parts
    parent_fd = _open_directory(root_fd, parts[:-1])
    temp = f".forgekit-{secrets.token_hex(16)}.tmp"
    fd = -1
    try:
        try:
            existing = os.stat(parts[-1], dir_fd=parent_fd, follow_symlinks=False)
        except FileNotFoundError:
            existing = None
        if existing and (not force or not stat.S_ISREG(existing.st_mode)):
            raise ValueError(f"Refusing to overwrite non-regular or existing file: {relative}")
        fd = os.open(
            temp, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600, dir_fd=parent_fd
        )
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as stream:
            fd = -1
            stream.write(text)
        if force:
            os.replace(temp, parts[-1], src_dir_fd=parent_fd, dst_dir_fd=parent_fd)
        else:
            os.link(
                temp, parts[-1], src_dir_fd=parent_fd, dst_dir_fd=parent_fd, follow_symlinks=False
            )
    finally:
        if fd >= 0:
            os.close(fd)
        try:
            os.unlink(temp, dir_fd=parent_fd)
        except FileNotFoundError:
            pass
        os.close(parent_fd)


@app.command("create")
def create_cmd(
    name: str = typer.Argument(..., help="Project name (letters, digits, hyphens or underscores)"),
    template: str = typer.Option(
        "python", "--template", "-t", help="Template: python, node, generic"
    ),
    path: str = typer.Option(".", "--path", "-p", help="Existing parent directory"),
    git: bool = typer.Option(False, "--git", help="Initialize git repository"),
    force: bool = typer.Option(False, "--force", help="Replace existing template files"),
    json: bool = typer.Option(False, "--json", help="Output as JSON"),
) -> None:
    """Create a project; existing files require --force and links are never followed."""

    def fail(message: str) -> None:
        if json:
            print_json({"error": message})
        else:
            console.print(f"[red]{message}[/red]")
        raise typer.Exit(1)

    if template not in TEMPLATES:
        fail(f"Unknown template: {template}. Available: {', '.join(TEMPLATES)}")
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_-]{0,63}", name):
        fail("Invalid project name: use letters, digits, hyphens or underscores")
    module = name.lower().replace("-", "_")
    if template == "python" and (not module.isidentifier() or keyword.iskeyword(module)):
        fail("Python project name must form a valid Python module name")
    if template == "node" and (name != name.lower() or "_" in name):
        fail("Node project names must use lowercase letters, digits and hyphens")
    try:
        parent = Path(path).expanduser().resolve()
    except (OSError, RuntimeError) as exc:
        fail(f"Could not resolve workspace parent: {exc}")
    if not parent.is_dir():
        fail(f"Parent is not a directory: {parent}")
    dest = parent / name
    try:
        parent_stat = parent.stat()
        try:
            dest_stat = dest.lstat()
        except FileNotFoundError:
            dest_stat = None
    except OSError as exc:
        fail(f"Could not inspect workspace destination: {exc}")
    if dest_stat and stat.S_ISLNK(dest_stat.st_mode):
        fail(f"Destination must not be a symbolic link: {dest}")
    if dest_stat and (not stat.S_ISDIR(dest_stat.st_mode) or not force):
        fail(f"Destination already exists: {dest}; use --force for an existing directory")
    if not (
        hasattr(os, "O_NOFOLLOW")
        and hasattr(os, "O_DIRECTORY")
        and os.open in os.supports_dir_fd
        and os.mkdir in os.supports_dir_fd
        and os.stat in os.supports_dir_fd
        and os.link in os.supports_dir_fd
        and os.unlink in os.supports_dir_fd
        and os.rename in os.supports_dir_fd
        and os.stat in os.supports_follow_symlinks
        and os.link in os.supports_follow_symlinks
    ):
        fail("Safe workspace creation is not supported on this platform")
    template_data = TEMPLATES[template]
    planned = [
        (
            rel.format(name=module if template == "python" else name),
            content.format(name=name, module=module),
        )
        for rel, content in template_data["files"].items()
    ]
    # Preflight the complete template before changing any existing project.
    for relative, _ in planned:
        current = dest
        parts = Path(relative).parts
        for index, part in enumerate(parts):
            current = current / part
            if current.is_symlink():
                fail(f"Refusing symbolic link in workspace: {current}")
            if index < len(parts) - 1 and current.exists() and not current.is_dir():
                fail(f"Expected a directory in workspace: {current}")
        if current.exists() and (not force or not current.is_file()):
            fail(f"Refusing to overwrite: {current}")
    created: list[str] = []
    git_msg = ""
    try:
        parent_fd = _open_existing_directory(parent)
        try:
            actual_parent = os.fstat(parent_fd)
            if (actual_parent.st_dev, actual_parent.st_ino) != (
                parent_stat.st_dev,
                parent_stat.st_ino,
            ):
                raise ValueError("Workspace parent changed during creation")
            if dest_stat is None:
                # A concurrent creation must fail, even when --force was passed.
                os.mkdir(name, dir_fd=parent_fd)
            root_fd = os.open(name, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW, dir_fd=parent_fd)
            try:
                actual_dest = os.fstat(root_fd)
                if dest_stat and (actual_dest.st_dev, actual_dest.st_ino) != (
                    dest_stat.st_dev,
                    dest_stat.st_ino,
                ):
                    raise ValueError("Workspace destination changed during creation")
                for relative, text in planned:
                    # A newly created project never overwrites concurrent files,
                    # even if --force was supplied for an initially absent path.
                    _write_workspace_file(root_fd, relative, text, force and dest_stat is not None)
                    created.append(str(dest / relative))
                if git:
                    fd_paths = (
                        Path("/proc/self/fd") / str(root_fd),
                        Path("/dev/fd") / str(root_fd),
                    )
                    git_cwd = next(
                        (candidate for candidate in fd_paths if candidate.is_dir()), None
                    )
                    if git_cwd is None:
                        raise OSError("Safe Git initialization requires descriptor-backed paths")
                    try:
                        result = run_command(["git", "init"], cwd=git_cwd, pass_fds=(root_fd,))
                    except (OSError, subprocess.TimeoutExpired) as exc:
                        raise OSError(f"Git initialization failed: {exc}") from exc
                    if result.returncode:
                        raise OSError(f"Git initialization failed: {result.stderr.strip()}")
                    git_msg = "Git initialized."
            finally:
                os.close(root_fd)
        finally:
            os.close(parent_fd)
    except (OSError, ValueError) as exc:
        fail(f"Could not create workspace: {exc}. Some created files may remain in {dest}.")
    if json:
        print_json(
            {
                "project": str(dest),
                "template": template,
                "created": created,
                "skipped": [],
                "git": git_msg,
            }
        )
    else:
        console.print(f"[green]✓ Project created: {dest} (template: {template})[/green]")
        for file in created:
            console.print(f"  [dim]+[/dim] {file}")
        if git_msg:
            console.print(git_msg)
        console.print("[dim]No package installation was performed.[/dim]")


@app.command("templates")
def templates_cmd(
    json: bool = typer.Option(False, "--json", help="Output as JSON"),
) -> None:
    """List available templates."""
    if json:
        print_json({k: v["description"] for k, v in TEMPLATES.items()})
        return

    table = create_table(title="Available Templates")
    table.add_column("Template", style="cyan")
    table.add_column("Description", style="white")
    table.add_column("Files", style="dim")
    for k, v in TEMPLATES.items():
        table.add_row(k, v["description"], ", ".join(list(v["files"].keys())[:4]))  # type: ignore
    console.print(table)
    console.print("[dim]Use: forge workspace create NAME --template TEMPLATE[/dim]")


@app.command("inspect")
def inspect_cmd(
    target: str = typer.Argument(..., help="Path to inspect"),
    json: bool = typer.Option(False, "--json", help="Output as JSON"),
) -> None:
    """Inspect a project directory."""
    p = Path(target).resolve()
    if not p.exists():
        cli_error(f"Path not found: {p}", json)

    info: dict[str, object] = {"path": str(p), "is_dir": p.is_dir(), "is_file": p.is_file()}
    if p.is_dir():
        try:
            entries = list(p.iterdir())
            info["entries"] = [e.name for e in entries[:30]]
            info["entry_count"] = len(entries)
            # Detect template type
            if (p / "pyproject.toml").exists() or (p / "setup.py").exists():
                info["detected_template"] = "python"
            elif (p / "package.json").exists():
                info["detected_template"] = "node"
            else:
                info["detected_template"] = "generic"
            info["has_git"] = (p / ".git").exists()
            info["has_readme"] = (p / "README.md").exists()
            info["has_gitignore"] = (p / ".gitignore").exists()
            # Use the same symlink-safe accounting as the files commands.
            from forgekit.services.filesystem_service import directory_size
            from forgekit.utils import format_bytes

            total = directory_size(p)["total_size"]

            info["total_size"] = total
            info["total_size_human"] = format_bytes(total)
        except PermissionError as e:
            info["error"] = str(e)

    if json:
        print_json(info)
        return

    table = create_table(title=f"Workspace: {p}")
    table.add_column("Property", style="cyan")
    table.add_column("Value", style="white")
    for k, v in info.items():
        if isinstance(v, list):
            v = ", ".join(str(x) for x in v[:10])
        table.add_row(k, str(v)[:100])
    console.print(table)
